package references

import "github.com/bradhannah/UltimaVRedux/internal/sprites/indexes"

// newMoonstoneItemReferences shares the lore across the eight phase identities.
func newMoonstoneItemReferences() map[Moonstone]InventoryItem {
	const description = "Blue moongates, generated by moonstones, generally focus on destinations in but a single world - the world in which they appear. Their power, awesome though it may seem, is limited, allowing the traveler to teleport only from the location of one moonstone to that of another. The moonstone the user travels to is determined by the phase of the moon that appears directly overhead in the sky. Through experimentation and observation, the moongate traveler can correlate the phases of the highest moon with the destination the gate will select."
	names := map[Moonstone]string{
		NewMoon: "NewMoon", CrescentWaxing: "CrescentWaxing", FirstQuarter: "FirstQuarter",
		GibbousWaxing: "GibbousWaxing", FullMoon: "FullMoon", GibbousWaning: "GibbousWaning",
		LastQuarter: "LastQuarter", CrescentWaning: "CrescentWaning",
	}
	items := make(map[Moonstone]InventoryItem, len(names))
	for phase, name := range names {
		attribution := "Compendium (Ultima VI)"
		if phase == GibbousWaning {
			attribution = "" // Preserve the existing player-facing source line.
		}
		//nolint:exhaustruct // Moonstones have shared lore and no duration or pickup override.
		items[phase] = InventoryItem{ItemName: name, ItemSprite: indexes.Moon,
			ItemDescription: description, ItemDescriptionAttribution: attribution}
	}

	return items
}
