func TestGetAllSearchLocationsPreservesSourceOrder(t *testing.T) {
	locations := GetAllSearchLocations()
	require.Len(t, locations, SearchLocationCount)
	for index, location := range locations {
		assert.Equal(t, index, location.Index)
		assert.Equal(t, SearchObjectClass(searchLocationObjectTypes[index]), location.ObjectClass)
		assert.Equal(t, searchLocationPayloads[index], location.Payload)
		assert.Equal(t, int(searchLocationMaps[index]), location.MapNumber)
		assert.Equal(t, int(searchLocationXs[index]), location.X)
		assert.Equal(t, int(searchLocationYs[index]), location.Y)
		if searchLocationLevels[index] == 0xff {
			assert.Equal(t, -1, location.Level)
		} else {
			assert.Equal(t, int(searchLocationLevels[index]), location.Level)
		}
	}
}

func TestDecodeSearchLocationItemUsesClassSpecificPayloadSemantics(t *testing.T) {
	locations := GetAllSearchLocations()
	tests := []struct {
		index     int
		item      Item
		quantity  int
		semantics string
		discovery string
	}{
		{0, MysticArmour, 1, "payload_is_equipment_id", "some armour!"},
		{1, MysticSword, 1, "payload_is_equipment_id", "a weapon!"},
		{12, HMSCape, 1, "payload_is_hms_cape_plans", "a scroll!"},
		{13, Key, 9, "payload_is_pickup_quantity", "a ring of keys!"},
		{14, SkullKeys, 5, "high_bit_selects_skull_keys", "a ring of keys!"},
		{15, GlassSword, 1, "payload_is_equipment_id", "a weapon!"},
		{21, Purple, 1, "payload_is_potion_subtype", "a potion!"},
		{24, ScrollKalXenCorp, 1, "payload_is_scroll_subtype", "a scroll!"},
		{26, Food, 10, "payload_is_pickup_quantity", "some food!"},
		{27, Torches, 3, "payload_is_pickup_quantity", "some torches!"},
		{28, RingInvisibility, 1, "payload_is_equipment_id", "a ring!"},
		{40, nil, 0, "payload_is_object_state", "a moldy corpse!"},
		{42, nil, 0, "payload_is_object_state", "a rotting body!"},
		{48, Gold, 99, "payload_is_pickup_quantity", "a sack of gold!"},
		{54, Gem, 4, "payload_is_pickup_quantity", "a gem!"},
	}

	for _, test := range tests {
		decoded := DecodeSearchLocationItem(locations[test.index])
		assert.Equal(t, test.item, decoded.Item, "index %d", test.index)
		assert.Equal(t, test.quantity, decoded.PickupQuantity, "index %d", test.index)
		assert.Equal(t, test.semantics, decoded.QuantitySemantics, "index %d", test.index)
		assert.Equal(t, test.discovery, decoded.DiscoveryText, "index %d", test.index)
		assert.False(t, decoded.Suspicious, "index %d: %s", test.index, decoded.EncodingNote)
	}
}

func TestEverySearchPayloadDecodesToCatalogOrWorldObject(t *testing.T) {
	for _, location := range GetAllSearchLocations() {
		decoded := DecodeSearchLocationItem(location)
		assert.False(t, decoded.Suspicious, "index %d: %s", location.Index, decoded.EncodingNote)
		assert.NotEmpty(t, decoded.DiscoveryText, "index %d", location.Index)
		if decoded.Classification == "inventory_item" {
			assert.NotNil(t, decoded.Item, "index %d", location.Index)
			assert.Positive(t, decoded.PickupQuantity, "index %d", location.Index)
		} else {
			assert.Equal(t, "world_object", decoded.Classification, "index %d", location.Index)
			assert.Zero(t, decoded.PickupQuantity, "index %d", location.Index)
		}
	}
}
