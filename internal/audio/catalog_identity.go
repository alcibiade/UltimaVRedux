func catalogAmbientNames() map[AmbientSoundType]string {
	names := make(map[AmbientSoundType]string)
	for id := range productionLibrary().Routing.Ambient {
		names[AmbientSoundType(id)] = id[len("ambient/"):]
	}

	return names
}
